// C++ program that uses \n and \t escape sequences
#include<iostream>
using namespace std;
int main()
{
	// to reproduce a 3-row staggered star pattern
	cout << "  ********    ********    ********    ********\n";
	cout << "\n\t********    ********    ********    ********\n";
	cout << "\n  ********    ********    ********    ********\n";
	return 0;
}